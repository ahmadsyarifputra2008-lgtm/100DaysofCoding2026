public class Day09 {
    public static void main(String[] args) {
        // KONSTANTA (final variabel)

        /*
         Konstanta adalah variabel yang nilainya tidak dapat diubah setelah diinisialisasi.
         Untuk mendeklarasikan konstanta, kita menggunakan kata kunci final.
        */

        //contoh penggunaan konstanta
        System.out.println("\nContoh penggunaan konstanta:");
        final double PI = 3.14159; // deklarasi konstanta PI dengan tipe data double
        System.out.println("nilai PI ="+PI+"\n");

        final byte HARI_SEMINGGU = 7;
        System.out.println("hari dalam seminggu = "+ HARI_SEMINGGU + " HARI");
        
        
    }
}
